// NEXT (audit P1) — the canonical object an ENROLLED passkey approves to add another passkey or to revoke one.
//
// It replaces `SPW-ENROLL-v1` (a bare string of the credential id and public key: no expiry, no request id, no action, no key
// id) for every credential after the first. The first passkey of a signer is still pinned with the operator's one-time setup
// token and nothing else (signer.ts `enroll`). The signer verifies this object itself: single use (`requestId`), a validity
// window of at most CRED_MAX_TTL_SEC, its own `keyId`, and the rules of each action (isolated-signer/src/signer.ts
// `credentialApply`). The SHA-256 of the bytes below is the WebAuthn challenge.
import { sha256 } from '@noble/hashes/sha2.js';
import { z } from 'zod';

export const CRED_DOMAIN = 'SPW-CRED-v2';
/** longest validity of a credential request, in seconds (expiresAt − createdAt) */
export const CRED_MAX_TTL_SEC = 300;

const B64U = (min: number, max: number) => z.string().regex(new RegExp(`^[A-Za-z0-9_-]{${min},${max}}$`));
export const CredentialRequestSchema = z.strictObject({
  v: z.literal(2),
  action: z.enum(['add', 'revoke']),
  /** generated by the server for this one request; the signer records it and refuses it a second time */
  requestId: z.uuid(),
  /** the signer this request is for */
  keyId: z.string().min(8).max(80),
  /** WebAuthn credential id, base64url without padding: the passkey to add, or the one to revoke */
  credentialId: B64U(16, 1024),
  /** `add` only: the COSE public key of the new passkey, base64url without padding. Absent for `revoke`. */
  publicKey: B64U(40, 2048).optional(),
  createdAt: z.number().int().positive(),
  expiresAt: z.number().int().positive(),
});
export type CredentialRequest = z.infer<typeof CredentialRequestSchema>;

const enc = new TextEncoder();
/**
 * Deterministic, length-prefixed, domain-separated serialization — the framing of intent.ts under another domain. Eight
 * fields, always all of them, always in this order; `publicKey` is the empty string for a revocation.
 */
export function credentialBytes(request: CredentialRequest): Uint8Array {
  const r = CredentialRequestSchema.parse(request);
  if ((r.action === 'add') !== (r.publicKey !== undefined)) throw new Error('a credential request names a public key when it adds a passkey, and only then');
  const fields: [string, string][] = [['v', String(r.v)], ['action', r.action], ['requestId', r.requestId], ['keyId', r.keyId],
    ['credentialId', r.credentialId], ['publicKey', r.publicKey ?? ''], ['createdAt', String(r.createdAt)], ['expiresAt', String(r.expiresAt)]];
  const parts: Uint8Array[] = [enc.encode(CRED_DOMAIN), new Uint8Array([0])];
  for (const [k, v] of fields) {
    const kb = enc.encode(k), vb = enc.encode(v);
    const head = new Uint8Array(6);
    new DataView(head.buffer).setUint16(0, kb.length);
    new DataView(head.buffer).setUint32(2, vb.length);
    parts.push(head, kb, vb);
  }
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let o = 0;
  for (const p of parts) { out.set(p, o); o += p.length; }
  return out;
}
export const credentialHash = (request: CredentialRequest): Uint8Array => sha256(credentialBytes(request));
