// The four Solana transactions of the Solana ↔ EVM USDC bridge (Circle CCTP V2). As on the EVM side there is NO outside
// transaction data: every message below is built from the approved intent (or the approved bridge record) and the pinned
// tables of cctp-sol.ts. The only outside bytes are the attested message and its attestation, checked field by field by
// verifyCctpMint (cctp.ts) before they are placed in a transaction.
//
//   burn    (Solana → EVM)  one instruction, deposit_for_burn: owner and rent payer = the wallet, source = the wallet's own USDC
//                           token account, mint recipient = the wallet's own EVM address, destination caller = anyone, plus the
//                           second signer the program needs: a fresh event account (generated by the signer, used once);
//   mint    (EVM → Solana)  one instruction, receive_message: payer and caller = the wallet, credited account = the wallet's
//                           own USDC token account (= the message's mintRecipient);
//   reclaim (Solana → EVM)  one instruction, reclaim_event_account: the rent of the event account back to the wallet;
//   token account           one instruction, CreateIdempotent of the wallet's own USDC token account (before a burn toward Solana).
//
// All four are Solana v1 messages (every account inline, no lookup table, compute budget in the header), as in the Jupiter path.
import { sha256 } from '@noble/hashes/sha2.js';
import { base58 } from '@scure/base';
import { z } from 'zod';
import { baseUnits } from './amounts.ts';
import { cctpBytes32, cctpEnd, cctpMessageHash, verifyCctpMint, CCTP_FINALITY_FAST, CCTP_FINALITY_STANDARD, CCTP_MAX_FEE_BPS, type CctpBridge, type CctpEnd, type CctpMessage } from './cctp.ts';
import {
  CCTP_SOL_CU, CCTP_SOL_EVENT_RENT, CCTP_SOL_LOADED_DATA_LIMIT, CCTP_SOL_MAX_CU_PRICE, CCTP_SOL_MESSAGE_TRANSMITTER, CCTP_SOL_NETWORK, CCTP_SOL_NONCE_RENT, CCTP_SOL_TOKEN_MESSENGER_MINTER,
  cctpSolCreateTokenAccountIx, cctpSolDepositForBurnIx, cctpSolReceiveIx, cctpSolReclaimIx, cctpSolTokenAccount, cctpSolUsdc, compileSolV1Signed,
} from './cctp-sol.ts';
import { getNetwork } from './networks.ts';
import { RENT_TOKEN_ACCOUNT, SOL_SIGNATURE_FEE } from './swap-sol.ts';
import type { Intent } from './intent.ts';

/** Lifetime and compute budget of a Solana transaction that is not described by an intent (mint, reclaim). */
export interface SolBudget { recentBlockhash: string; lastValidBlockHeight: number; computeUnitLimit: number; computeUnitPrice: string }

const pubkey = (s: string) => { let b: Uint8Array; try { b = base58.decode(s); } catch { throw new Error('bad Solana address'); } if (b.length !== 32) throw new Error('bad Solana address'); return s; };
const hex = (s: string) => { if (!/^0x([0-9a-fA-F]{2})*$/.test(s)) throw new Error('not hex'); return Uint8Array.from(Buffer.from(s.slice(2), 'hex')); };
function budget(g: { recentBlockhash: string; computeUnitLimit: number; computeUnitPrice: string }, min: number, max: number): { priority: bigint } {
  pubkey(g.recentBlockhash);
  if (/^1{32,44}$/.test(g.recentBlockhash)) throw new Error('blockhash is zero');
  if (!Number.isInteger(g.computeUnitLimit) || g.computeUnitLimit < min || g.computeUnitLimit > max) throw new Error('compute-unit limit out of range');
  if (typeof g.computeUnitPrice !== 'string' || !/^(0|[1-9]\d{0,18})$/.test(g.computeUnitPrice)) throw new Error('malformed compute-unit price');
  const price = BigInt(g.computeUnitPrice);
  if (price > CCTP_SOL_MAX_CU_PRICE) throw new Error('compute-unit price above the ceiling');
  return { priority: (BigInt(g.computeUnitLimit) * price + 999_999n) / 1_000_000n };
}

// ---------------------------------------------------------------------------------------------------------------------
// Solana → EVM: the burn

export interface CctpSolBurn { dst: CctpEnd; amount: bigint; maxFee: bigint; /** bytes32 of the wallet's EVM address */ mintRecipient: string; /** two signatures + priority fee, exact */ networkFee: bigint; priority: bigint; /** refundable event-account deposit counted in the fee ceiling */ deposit: bigint }

/** Check every field of a bridge intent whose source is Solana against the pinned tables. Throws on any mismatch. */
export function verifyCctpSolBurn(i: Intent): CctpSolBurn {
  const n = getNetwork(i.network), b = i.bridge;
  if (n.family !== 'sol' || i.network !== CCTP_SOL_NETWORK || !i.sol || !b) throw new Error('not a Solana bridge intent');
  if (i.swap || i.xswap || i.evm || i.btc || i.x || i.venueDeposit || i.memo !== undefined) throw new Error('unexpected intent section');
  if (b.provider !== 'cctp') throw new Error('unknown bridge provider');
  if (i.chainRef !== n.chainRef) throw new Error('chain identity mismatch');
  const dst = cctpEnd(b.toNetwork);
  if (!dst || dst.family !== 'evm') throw new Error('CCTP execution is not enabled on the destination network');
  if (b.toDomain !== dst.domain) throw new Error('destination domain does not match the destination network');
  if (b.messenger !== CCTP_SOL_TOKEN_MESSENGER_MINTER) throw new Error('messenger is not the pinned TokenMessengerMinterV2 program');
  if (b.transmitter !== CCTP_SOL_MESSAGE_TRANSMITTER) throw new Error('transmitter is not the pinned MessageTransmitterV2 program');
  pubkey(i.from);
  if (i.to !== i.from) throw new Error('a bridge must deliver to the wallet itself');
  if (b.recipient === undefined) throw new Error('a bridge from Solana names the wallet\'s address on the destination network');
  const mintRecipient = cctpBytes32(b.recipient); // throws unless it is an EVM address
  const usdc = cctpSolUsdc();
  if (i.asset !== usdc.id) throw new Error('only the registry USDC can be bridged');
  if (i.symbol !== 'USDC' || i.decimals !== usdc.decimals) throw new Error('asset metadata mismatch');
  const amount = baseUnits(i.amount), maxFee = baseUnits(b.maxFee);
  if (amount <= 0n || amount >= 1n << 64n) throw new Error('amount out of range');
  if (maxFee >= amount) throw new Error('CCTP fee ceiling must be below the amount');
  if (maxFee * 10_000n > amount * CCTP_MAX_FEE_BPS) throw new Error('CCTP fee ceiling above 1 % of the amount');
  if (b.minFinalityThreshold !== CCTP_FINALITY_FAST && b.minFinalityThreshold !== CCTP_FINALITY_STANDARD) throw new Error('finality threshold must be 1000 (Fast) or 2000 (Standard)');
  if (b.approveGas !== '0') throw new Error('a burn on Solana has no approval step');
  if (i.sol.createAta) throw new Error('a burn creates no token account');
  const { priority } = budget(i.sol, CCTP_SOL_CU.burnMin, CCTP_SOL_CU.burnMax);
  const networkFee = 2n * SOL_SIGNATURE_FEE + priority; // the wallet and the event account both sign
  // the event account's rent leaves the wallet in the same transaction: it is counted inside the approved (and policy) ceiling
  if (networkFee + CCTP_SOL_EVENT_RENT > baseUnits(i.maxFee)) throw new Error('fee and event-account deposit exceed the approved maximum');
  return { dst, amount, maxFee, mintRecipient, networkFee, priority, deposit: CCTP_SOL_EVENT_RENT };
}

/** The burn message, rebuilt from the intent alone. `eventAccount` is the public key of the keypair the signer generated for it. */
export function buildCctpSolBurnMessage(i: Intent, eventAccount: string): Uint8Array {
  const v = verifyCctpSolBurn(i);
  pubkey(eventAccount);
  if (eventAccount === i.from || eventAccount === cctpSolTokenAccount(i.from)) throw new Error('bad event account');
  const ix = cctpSolDepositForBurnIx({ owner: i.from, eventAccount, amount: v.amount, destinationDomain: v.dst.domain, mintRecipientHex: v.mintRecipient, maxFee: v.maxFee, minFinalityThreshold: i.bridge!.minFinalityThreshold });
  return compileSolV1Signed({ payer: i.from, signers: [eventAccount], blockhash: i.sol!.recentBlockhash, instructions: [ix], computeUnitLimit: i.sol!.computeUnitLimit, priorityFeeLamports: v.priority, loadedAccountsDataSizeLimit: CCTP_SOL_LOADED_DATA_LIMIT });
}

/**
 * What the program will store in the event account for this burn: the message before attestation (nonce, executed finality,
 * executed fee and expiration all zero). Used to check a simulation, and by tests.
 */
export function expectedCctpSolSourceMessage(i: Intent): CctpMessage {
  const v = verifyCctpSolBurn(i), src = cctpEnd(i.network)!, zero = '0'.repeat(64);
  return { version: 1, sourceDomain: src.domain, destinationDomain: v.dst.domain, nonce: zero, sender: src.messenger, recipient: v.dst.messenger, destinationCaller: zero, minFinalityThreshold: i.bridge!.minFinalityThreshold, finalityThresholdExecuted: 0,
    body: { version: 1, burnToken: src.usdc, mintRecipient: v.mintRecipient, amount: v.amount, messageSender: Buffer.from(base58.decode(i.from)).toString('hex'), maxFee: v.maxFee, feeExecuted: 0n, expirationBlock: 0n } };
}

// ---------------------------------------------------------------------------------------------------------------------
// EVM → Solana: the mint

/** receive_message for an approved bridge. `feeCeiling` is the signer policy's fee ceiling for Solana (lamports). */
export function buildCctpSolMintMessage(b: CctpBridge, message: string, attestation: string, g: SolBudget, feeCeiling: bigint): { msg: Uint8Array; networkFee: bigint; tokenAccount: string } {
  const v = verifyCctpMint(b, message, attestation);
  const dst = cctpEnd(b.toNetwork);
  if (!dst || dst.family !== 'sol' || b.recipient === undefined) throw new Error('this mint is not on Solana');
  const me = pubkey(b.recipient), tokenAccount = cctpSolTokenAccount(me);
  // verifyCctpMint already required mintRecipient = this account; the instruction is given the same derived account
  if (v.msg.body.mintRecipient !== Buffer.from(base58.decode(tokenAccount)).toString('hex')) throw new Error('message mints to another address');
  const { priority } = budget(g, CCTP_SOL_CU.mintMin, CCTP_SOL_CU.mintMax);
  const networkFee = SOL_SIGNATURE_FEE + priority;
  // the used-nonce record's rent is paid by the wallet in the same transaction (not refundable)
  if (networkFee + CCTP_SOL_NONCE_RENT > feeCeiling) throw new Error('mint fee above the policy ceiling of the destination network');
  const ix = cctpSolReceiveIx({ payer: me, message: hex(message), attestation: hex(attestation), nonceHex: v.msg.nonce, sourceDomain: v.msg.sourceDomain, burnTokenHex: v.msg.body.burnToken, recipientTokenAccount: tokenAccount });
  const msg = compileSolV1Signed({ payer: me, signers: [], blockhash: g.recentBlockhash, instructions: [ix], computeUnitLimit: g.computeUnitLimit, priorityFeeLamports: priority, loadedAccountsDataSizeLimit: CCTP_SOL_LOADED_DATA_LIMIT });
  return { msg, networkFee, tokenAccount };
}

// ---------------------------------------------------------------------------------------------------------------------
// Solana → EVM: the event-account deposit back to the wallet

/** reclaim_event_account for the event account recorded with an approved burn. The attested message must be that bridge's own. */
export function buildCctpSolReclaimMessage(b: CctpBridge, eventAccount: string, message: string, attestation: string, g: SolBudget, feeCeiling: bigint): { msg: Uint8Array; networkFee: bigint; messageHash: string } {
  if (b.fromNetwork !== CCTP_SOL_NETWORK) throw new Error('this bridge did not start on Solana');
  verifyCctpMint(b, message, attestation); // the program compares the source fields with the stored message and checks the attestation
  const me = pubkey(b.wallet);
  pubkey(eventAccount);
  if (eventAccount === me || eventAccount === cctpSolTokenAccount(me)) throw new Error('bad event account');
  const { priority } = budget(g, CCTP_SOL_CU.reclaimMin, CCTP_SOL_CU.reclaimMax);
  const networkFee = SOL_SIGNATURE_FEE + priority;
  if (networkFee > feeCeiling) throw new Error('fee above the policy ceiling');
  const ix = cctpSolReclaimIx({ payee: me, eventAccount, message: hex(message), attestation: hex(attestation) });
  const msg = compileSolV1Signed({ payer: me, signers: [], blockhash: g.recentBlockhash, instructions: [ix], computeUnitLimit: g.computeUnitLimit, priorityFeeLamports: priority, loadedAccountsDataSizeLimit: CCTP_SOL_LOADED_DATA_LIMIT });
  return { msg, networkFee, messageHash: cctpMessageHash(message) };
}

const enc = new TextEncoder();
const lines = (...parts: string[]) => enc.encode(parts.join('\n'));
/** Passkey challenge for a RE-SIGNATURE of a mint on Solana (the first one is covered by the burn approval). SHA-256 of these bytes. */
export const cctpSolMintRetryBytes = (proposalId: string, messageHash: string, g: SolBudget): Uint8Array =>
  lines('SPW-BRIDGE-MINT-SOL-v1', proposalId, messageHash, g.recentBlockhash, String(g.lastValidBlockHeight), String(g.computeUnitLimit), g.computeUnitPrice);
/** Passkey challenge for the reclaim of an event-account deposit: every reclaim signature needs the owner. SHA-256 of these bytes. */
export const cctpSolReclaimBytes = (proposalId: string, eventAccount: string, messageHash: string, g: SolBudget): Uint8Array =>
  lines('SPW-BRIDGE-RECLAIM-v1', proposalId, eventAccount, messageHash, g.recentBlockhash, String(g.lastValidBlockHeight), String(g.computeUnitLimit), g.computeUnitPrice);

// ---------------------------------------------------------------------------------------------------------------------
// The wallet's own USDC token account (needed before any burn toward Solana)

const U = z.string().regex(/^(0|[1-9]\d{0,18})$/);
/** What the owner approves to open the wallet's own USDC token account on Solana: nothing but that account can be created. */
export const SolTokenAccountSchema = z.strictObject({
  v: z.literal(1), requestId: z.uuid(), keyId: z.string().min(8).max(80), network: z.literal(CCTP_SOL_NETWORK), chainRef: z.string().min(1).max(80),
  owner: z.string().min(32).max(44), mint: z.string().min(32).max(44), tokenAccount: z.string().min(32).max(44), maxFee: U,
  createdAt: z.number().int().positive(), expiresAt: z.number().int().positive(), policyVersion: z.number().int().nonnegative(),
  sol: z.strictObject({ recentBlockhash: z.string().min(32).max(44), lastValidBlockHeight: z.number().int().positive(), computeUnitLimit: z.number().int().min(1).max(400_000), computeUnitPrice: U }),
});
export type SolTokenAccountRequest = z.infer<typeof SolTokenAccountSchema>;
/** Domain-separated, length-prefixed hash of the request: the passkey challenge. */
export function solTokenAccountHash(r: SolTokenAccountRequest): Uint8Array {
  const q = SolTokenAccountSchema.parse(r);
  const f: [string, string][] = [['v', '1'], ['requestId', q.requestId], ['keyId', q.keyId], ['network', q.network], ['chainRef', q.chainRef], ['owner', q.owner], ['mint', q.mint], ['tokenAccount', q.tokenAccount], ['maxFee', q.maxFee],
    ['createdAt', String(q.createdAt)], ['expiresAt', String(q.expiresAt)], ['policyVersion', String(q.policyVersion)],
    ['sol.recentBlockhash', q.sol.recentBlockhash], ['sol.lastValidBlockHeight', String(q.sol.lastValidBlockHeight)], ['sol.computeUnitLimit', String(q.sol.computeUnitLimit)], ['sol.computeUnitPrice', q.sol.computeUnitPrice]];
  const parts: Uint8Array[] = [enc.encode('SPW-SOL-TOKEN-ACCOUNT-v1'), new Uint8Array([0])];
  for (const [k, v] of f) { const kb = enc.encode(k), vb = enc.encode(v), head = new Uint8Array(6); new DataView(head.buffer).setUint16(0, kb.length); new DataView(head.buffer).setUint32(2, vb.length); parts.push(head, kb, vb); }
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0)); let o = 0; for (const p of parts) { out.set(p, o); o += p.length; }
  return sha256(out);
}
/** One instruction: CreateIdempotent of the owner's associated USDC account, paid by the owner. Fee + rent bound ≤ the approved ceiling. */
export function buildSolTokenAccountMessage(r: SolTokenAccountRequest): { msg: Uint8Array; networkFee: bigint; rentMax: bigint } {
  const q = SolTokenAccountSchema.parse(r), n = getNetwork(q.network);
  if (q.chainRef !== n.chainRef) throw new Error('chain identity mismatch');
  pubkey(q.owner);
  if (q.mint !== cctpSolUsdc().id) throw new Error('only the registry USDC token account can be opened here');
  if (q.tokenAccount !== cctpSolTokenAccount(q.owner)) throw new Error('token account is not the wallet\'s own associated USDC account');
  const { priority } = budget(q.sol, CCTP_SOL_CU.ataMin, CCTP_SOL_CU.ataMax);
  const networkFee = SOL_SIGNATURE_FEE + priority;
  if (networkFee + RENT_TOKEN_ACCOUNT > BigInt(q.maxFee)) throw new Error('fee and token-account deposit exceed the approved maximum');
  const msg = compileSolV1Signed({ payer: q.owner, signers: [], blockhash: q.sol.recentBlockhash, instructions: [cctpSolCreateTokenAccountIx(q.owner)], computeUnitLimit: q.sol.computeUnitLimit, priorityFeeLamports: priority, loadedAccountsDataSizeLimit: CCTP_SOL_LOADED_DATA_LIMIT });
  return { msg, networkFee, rentMax: RENT_TOKEN_ACCOUNT };
}
