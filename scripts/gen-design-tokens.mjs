#!/usr/bin/env node
// SP Wallet Design System (NEXT) — design/tokens.json → apps/web/src/tokens.css + design/generated/SPWalletTokens.swift.
// `--check` regenerates in memory and fails when a committed output differs (CI / preflight). Contrast pairs are verified on
// every run: a token change that drops a text pair under 4.5:1 does not generate.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const T = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));
const check = process.argv.includes('--check');
const keys = (o) => Object.keys(o).filter((k) => !k.startsWith('$'));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase()).replace(/_/g, '-');
const camel = (s) => s.replace(/[_-]([a-z0-9])/g, (_, c) => c.toUpperCase());

// ── colour maths ─────────────────────────────────────────────────────────────────────────────────────────────────────────
const rgba = (hex) => { const h = hex.replace('#', ''); const n = (i) => parseInt(h.slice(i, i + 2), 16); return { r: n(0), g: n(2), b: n(4), a: h.length === 8 ? n(6) / 255 : 1 }; };
const over = (top, under) => ({ r: top.r * top.a + under.r * (1 - top.a), g: top.g * top.a + under.g * (1 - top.a), b: top.b * top.a + under.b * (1 - top.a), a: 1 });
const lum = ({ r, g, b }) => { const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }; return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b); };
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const cssColor = (hex) => { const c = rgba(hex); return c.a === 1 ? hex.slice(0, 7) : `rgba(${c.r}, ${c.g}, ${c.b}, ${+c.a.toFixed(3)})`; };

const problems = [], report = [];
for (const mode of ['light', 'dark']) {
  for (const [fg, bg] of T.contrast) {
    const under = rgba(T.color[bg][mode]), r = ratio(over(rgba(T.color[fg][mode]), under), under);
    report.push(`${mode.padEnd(5)} ${fg.padEnd(10)} on ${bg.padEnd(8)} ${r.toFixed(2)}`);
    if (r < 4.5) problems.push(`${mode}: ${fg} on ${bg} = ${r.toFixed(2)} (< 4.5)`);
  }
}
// text on the balance card: checked against the base with EVERY aurora light at full strength at once (lighter than any real point)
{ let worst = rgba(T.gradient.aurora.base);
  for (const l of T.gradient.aurora.lights) worst = over({ ...rgba(l.color), a: l.alpha }, worst);
  for (const fg of ['heroInk', 'heroMute']) { const r = ratio(rgba(T.color[fg].light), worst); report.push(`hero  ${fg.padEnd(10)} on aurora   ${r.toFixed(2)}`); if (r < 4.5) problems.push(`${fg} on the aurora's lightest possible point = ${r.toFixed(2)} (< 4.5)`); } }
if (problems.length) { console.error('design tokens: contrast below 4.5:1\n  ' + problems.join('\n  ')); process.exit(1); }

// ── CSS ──────────────────────────────────────────────────────────────────────────────────────────────────────────────────
const HEAD = 'GENERATED by scripts/gen-design-tokens.mjs from design/tokens.json — do not edit.';
const rem = (px) => `${+(px / 16).toFixed(4)}rem`;
const themeVars = (mode) => [
  ...keys(T.color).map((k) => `  --${kebab(k)}: ${cssColor(T.color[k][mode])};`),
  ...T.series.names.map((n, i) => `  --series-${n}: ${T.series[mode][i]};`),
  ...keys(T.elevation).map((k) => `  --${k}: ${T.elevation[k][mode]};`),
  `  color-scheme: ${mode};`,
].join('\n');
const aurora = () => { const g = T.gradient.aurora; const l = g.lights.map((x) => { const c = rgba(x.color); return `radial-gradient(${Math.round(x.radius * 100)}% ${Math.round(x.radius * 100)}% at ${Math.round(x.x * 100)}% ${Math.round(x.y * 100)}%, rgba(${c.r}, ${c.g}, ${c.b}, ${x.alpha}), transparent 70%)`; }); return [...l, g.base].join(', '); };
const css = `/* ${HEAD} */
:root {
${keys(T.space).map((k) => `  --space-${k}: ${rem(T.space[k])};`).join('\n')}
${keys(T.layout).map((k) => `  --${kebab(k)}: ${T.layout[k] >= 600 ? T.layout[k] + 'px' : rem(T.layout[k])};`).join('\n')}
${keys(T.radius).map((k) => `  --radius-${k}: ${T.radius[k]}px;`).join('\n')}
${keys(T.motion.duration).map((k) => `  --dur-${k}: ${T.motion.duration[k]}ms;`).join('\n')}
${keys(T.motion.easing).map((k) => `  --ease-${k}: cubic-bezier(${T.motion.easing[k].join(', ')});`).join('\n')}
  --aurora: ${aurora()};
}
:root, [data-theme='light'] {
${themeVars('light')}
}
[data-theme='dark'] {
${themeVars('dark')}
}
@media (prefers-color-scheme: dark) {
  [data-theme='system'] {
${themeVars('dark').replace(/^/gm, '  ')}
  }
}
@media (prefers-reduced-motion: reduce) {
  :root { ${keys(T.motion.duration).map((k) => `--dur-${k}: 0ms;`).join(' ')} }
}
/* type roles: sizes in rem, so the reader's text-size preference applies */
${keys(T.type).map((k) => { const t = T.type[k]; return `.t-${kebab(k)} { font-size: ${rem(t.size)}; font-weight: ${t.weight}; letter-spacing: ${t.tracking}em; line-height: ${t.lineHeight}; font-variant-numeric: ${t.figures}-nums;${t.uppercase ? ' text-transform: uppercase;' : ''}${t.mono ? ' font-family: var(--font-mono);' : ''}${k === 'display' || k.startsWith('title') ? ' font-family: var(--font-display);' : ''} }`; }).join('\n')}
/* life-cycle tones */
${keys(T.status).map((k) => `[data-lifecycle='${k}'] { --tone: var(--${T.status[k].tone}); }`).join('\n')}
`;

// ── Swift ────────────────────────────────────────────────────────────────────────────────────────────────────────────────
const sw = (hex) => { const c = rgba(hex); return `RGBA(${(c.r / 255).toFixed(4)}, ${(c.g / 255).toFixed(4)}, ${(c.b / 255).toFixed(4)}, ${c.a.toFixed(4)})`; };
const weight = (w) => (w >= 700 ? '.bold' : w >= 600 ? '.semibold' : w >= 500 ? '.medium' : '.regular');
const swift = `// ${HEAD}
// swiftlint:disable all
import SwiftUI

/// Raw values of the SP Wallet Design System. Views use the semantic accessors of SPWalletUI (Color.sp…, Font.sp…), never these numbers directly.
public enum SPTokens {
    public static let version = "${T.version}"
    public struct RGBA: Sendable, Equatable { public let r, g, b, a: Double; public init(_ r: Double, _ g: Double, _ b: Double, _ a: Double) { self.r = r; self.g = g; self.b = b; self.a = a } }
    public struct Pair: Sendable, Equatable { public let light, dark: RGBA }

    public enum Palette {
${keys(T.color).map((k) => `        /// ${T.color[k].role}\n        public static let ${camel(k)} = Pair(light: ${sw(T.color[k].light)}, dark: ${sw(T.color[k].dark)})`).join('\n')}
    }
    public enum Series {
        public static let light: [RGBA] = [${T.series.light.map(sw).join(', ')}]
        public static let dark: [RGBA] = [${T.series.dark.map(sw).join(', ')}]
    }
    public enum Aurora {
        public struct Light: Sendable { public let color: RGBA; public let x, y, radius: Double }
        public static let base = ${sw(T.gradient.aurora.base)}
        public static let lights: [Light] = [${T.gradient.aurora.lights.map((l) => `Light(color: ${sw(l.color + Math.round(l.alpha * 255).toString(16).padStart(2, '0'))}, x: ${l.x}, y: ${l.y}, radius: ${l.radius})`).join(', ')}]
    }
    public struct TypeRole: Sendable { public let size: Double; public let weight: Font.Weight; public let tracking: Double; public let lineHeight: Double; public let tabular: Bool; public let uppercase: Bool; public let mono: Bool; public let style: Font.TextStyle }
    public enum TypeScale {
${keys(T.type).map((k) => { const t = T.type[k]; return `        /// ${t.role}\n        public static let ${camel(k)} = TypeRole(size: ${t.size}, weight: ${weight(t.weight)}, tracking: ${t.tracking}, lineHeight: ${t.lineHeight}, tabular: ${t.figures === 'tabular'}, uppercase: ${!!t.uppercase}, mono: ${!!t.mono}, style: .${t.appleStyle})`; }).join('\n')}
    }
    public enum Space { ${keys(T.space).map((k) => `public static let s${k}: CGFloat = ${T.space[k]}`).join('; ')} }
    public enum Layout { ${keys(T.layout).map((k) => `public static let ${camel(k)}: CGFloat = ${T.layout[k]}`).join('; ')} }
    public enum Radius { ${keys(T.radius).map((k) => `public static let ${k}: CGFloat = ${T.radius[k]}`).join('; ')} }
    public struct Shadow: Sendable { public let y, blur, opacity: Double }
    public enum Elevation { ${keys(T.elevation).map((k) => `public static let ${k} = Shadow(y: ${T.elevation[k].apple.y}, blur: ${T.elevation[k].apple.blur}, opacity: ${T.elevation[k].apple.opacity})`).join('; ')} }
    public enum Motion {
        ${keys(T.motion.duration).map((k) => `public static let ${k}: Double = ${T.motion.duration[k] / 1000}`).join('; ')}
        public static let springResponse: Double = ${T.motion.appleSpring.response}; public static let springDamping: Double = ${T.motion.appleSpring.damping}
    }
    public enum Tone: String, Sendable, CaseIterable { case mute, accent, positive, negative, caution }
    public struct Status: Sendable { public let tone: Tone; public let symbol: String; public let fr: String; public let en: String }
    /// The transfer life cycle (API field \`lifecycle\`): one tone, one symbol, one word per value on every platform.
    public static let status: [String: Status] = [
${keys(T.status).map((k) => { const s = T.status[k]; return `        "${k}": Status(tone: .${s.tone}, symbol: "${s.symbol}", fr: "${s.fr}", en: "${s.en}"),`; }).join('\n')}
    ]
}
`;

// ── JSON for the web (status vocabulary) ─────────────────────────────────────────────────────────────────────────────────
const ts = `// ${HEAD}
export const DESIGN_VERSION = '${T.version}';
export type Tone = 'mute' | 'accent' | 'positive' | 'negative' | 'caution';
export const LIFECYCLE_STATUS = ${JSON.stringify(Object.fromEntries(keys(T.status).map((k) => [k, T.status[k]])), null, 2)} as const satisfies Record<string, { tone: Tone; symbol: string; fr: string; en: string }>;
export type LifecycleKey = keyof typeof LIFECYCLE_STATUS;
export const SERIES = ${JSON.stringify(T.series.names)} as const;
`;

const outs = [['apps/web/src/tokens.css', css], ['apps/web/src/tokens.gen.ts', ts], ['design/generated/SPWalletTokens.swift', swift]];
let stale = 0;
for (const [rel, text] of outs) {
  const p = resolve(root, rel);
  if (check) { let cur = ''; try { cur = readFileSync(p, 'utf8'); } catch { /* missing */ } if (cur !== text) { console.error(`design tokens: ${rel} is not up to date — run node scripts/gen-design-tokens.mjs`); stale += 1; } }
  else { mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, text); }
}
if (stale) process.exit(1);
if (!check) console.log(report.join('\n') + `\ndesign tokens ${T.version}: ${outs.map((o) => o[0]).join(', ')}`);
