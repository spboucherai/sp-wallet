    def wait_for_order(
        self, order_id: str, *, timeout: float = 60.0, poll_interval: float = 1.0, until: Callable[[m.Order], bool] | None = None
    ) -> m.OrderDetail:
        """Reads the order until it is final (FILLED, CANCELLED, REJECTED, FAILED) or `until(order)` is true.
        UNKNOWN is not final and not a failure: the wait continues. Raises WaitTimeout — which is not an order
        failure — when `timeout` seconds elapse first; `error.last` is the last answer."""
        done = until if until is not None else is_terminal_order
        started = time.monotonic()
        while True:
            last = self.get_order(order_id)
            if done(last.order):
                return last
            left = timeout - (time.monotonic() - started)
            if left <= 0:
                raise WaitTimeout(
                    f"order {order_id} is not final after {timeout:g} s (last status: {last.order.status}); it has not failed — keep reading it", last
                )
            self._sleep(min(poll_interval, left))

