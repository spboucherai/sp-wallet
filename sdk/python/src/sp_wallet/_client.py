    # ============================================================================================================ internals
    def _order_body(
        self, *, side: str, order_type: str, mode: str, reduce_only: Any, tif: Any, slippage_bps: Any, client_order_id: Any, account_id: Any, **sizing: Any
    ) -> dict[str, Any]:
        instrument, size, notional, price, trigger = self._order_fields(**sizing)
        if size is None:
            assert notional is not None
            size = self._size_from_market(instrument, notional, price, self.get_market(instrument))
        return self._body(
            m.OrderRequest, mode=mode, account_id=account_id, instrument=instrument, side=side, type=order_type, size=size, price=price,
            trigger_price=trigger, reduce_only=reduce_only, tif=tif, slippage_bps=slippage_bps, client_order_id=client_order_id,
        )  # fmt: skip

    def _get(self, model: type[M], path: str, query: Mapping[str, Any] | None = None) -> M:
        call = self._prepare("GET", path, query, None, None)
        data, meta = self._send(call)
        return self._parse(model, data, meta, call)

    def _write(self, method: str, path: str, body: Any, idempotency_key: str | None) -> WriteResult:
        if method == "GET":
            raise ConfigurationError("a write is POST or DELETE")
        call = self._prepare(method, path, None, body, idempotency_key)
        data, meta = self._send(call)
        return self._parse(WriteResult, data, meta, call)

    def _send(self, call: Call) -> tuple[Any, Any]:
        attempt = 0
        while True:
            failure: Exception | None = None
            response: httpx.Response | None = None
            try:
                response = self._http.request(
                    call.method, call.url, params=call.params or None, content=call.content, headers=self._headers(call), timeout=call.timeout
                )
            except httpx.HTTPError as exc:
                failure = exc
            # decided OUTSIDE the except block: the transport's exception (which references the request and its
            # Authorization header) must not become the context of what this SDK raises
            if response is None:
                assert failure is not None
                outcome: Any = self._transport_failed(call, attempt, failure)
            else:
                outcome = self._answered(call, attempt, response.status_code, response.headers, response.text)
            if isinstance(outcome, Retry):
                self._sleep(outcome.delay)
                attempt += 1
                continue
            return outcome  # type: ignore[no-any-return]
