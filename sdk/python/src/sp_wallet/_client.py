    def preview_order(
        self,
        *,
        side: Literal["buy", "sell"],
        order_type: Literal["limit", "market", "stop_market", "stop_limit", "take_profit_market", "take_profit_limit"],
        instrument: str | None = None,
        exchange: str | None = None,
        symbol: str | None = None,
        size: Decimalish = None,
        notional_usdc: Decimalish = None,
        mode: Mode = "paper",
        price: Decimalish = None,
        trigger_price: Decimalish = None,
        reduce_only: bool | None = None,
        tif: Literal["gtc", "ioc", "alo"] | None = None,
        slippage_bps: int | None = None,
        client_order_id: str | None = None,
        account_id: str | None = None,
        idempotency_key: str | None = None,
    ) -> WriteResult:
        """POST /orders/preview — risk check and estimate; places nothing. Scope `orders:prepare`.

        `instrument` is `venue:symbol` (or give `exchange` + `symbol`). Size the order with `size` (base units) or with
        `notional_usdc` — a client-side convenience, not a field of the API: the SDK reads the market and computes
        size = floor(notional / mark price, lot size). Amounts are decimal strings, `Decimal` or `int`; never a float.
        `mode` defaults to "paper".
        """
