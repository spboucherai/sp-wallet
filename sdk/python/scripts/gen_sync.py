"""Generates src/sp_wallet/_client.py (synchronous SPWallet) from src/sp_wallet/_async_client.py (AsyncSPWallet).

    uv run python scripts/gen_sync.py            write the file
    uv run python scripts/gen_sync.py --check    exit 1 when the committed file is not what the async source gives

One implementation, two clients: the same methods, the same retry and idempotency behaviour, by construction.
tests/test_models_drift.py runs the check.
"""

from __future__ import annotations

import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent / "src" / "sp_wallet"
SOURCE, OUTPUT = SRC / "_async_client.py", SRC / "_client.py"

HEADER = '''"""SPWallet — synchronous client of the SP Trading API (docs/openapi/trading-v1.json), on httpx.Client.

GENERATED by scripts/gen_sync.py from _async_client.py — do not edit (a test fails when the two differ).
"""

'''
REPLACEMENTS = [
    ("from collections.abc import AsyncIterator, Awaitable, Callable, Mapping", "from collections.abc import Callable, Iterator, Mapping"),
    ("AsyncSPWallet", "SPWallet"),
    ("httpx.AsyncClient", "httpx.Client"),
    ("async def ", "def "),
    ("await ", ""),
    ("__aenter__", "__enter__"),
    ("__aexit__", "__exit__"),
    ("self._http.aclose()", "self._http.close()"),
    ("def aclose(", "def close("),
    ("self.aclose()", "self.close()"),
    ("asyncio.sleep", "time.sleep"),
    ("import asyncio\n", ""),
    ("Callable[[float], Awaitable[None]]", "Callable[[float], None]"),
    ("AsyncIterator[", "Iterator["),
]


def generate(source: str) -> str:
    body = source[source.index("from __future__") :]
    for old, new in REPLACEMENTS:
        if old not in body:
            raise ValueError(f"gen_sync: {old!r} is not in the async source any more — update REPLACEMENTS")
        body = body.replace(old, new)
    for left in ("async ", "await", "Awaitable", "asyncio", "Async"):
        if left in body:
            raise ValueError(f"gen_sync: {left!r} is left in the generated synchronous client")
    return HEADER + body


def main() -> int:
    text = generate(SOURCE.read_text())
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print("src/sp_wallet/_client.py is out of date: run `uv run python scripts/gen_sync.py`", file=sys.stderr)
            return 1
        print("src/sp_wallet/_client.py is up to date")
        return 0
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
